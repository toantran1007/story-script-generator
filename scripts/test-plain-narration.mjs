import assert from 'node:assert/strict'
import { createLoader } from './lib/load-local-ts.mjs'
import { harness } from './test-chapter-memory.mjs'
import { bad, good, packet } from './test-text-repetition.mjs'
const load = createLoader()
const { plainNarration } = load('src/shared/plainNarration.ts')
const { applyChapterCorrection } = load('src/renderer/src/services/chapterCorrection.ts')
const { applyMemoryPayload } = load('src/renderer/src/services/detailedMemory.ts')
const { hasTargetLanguageLeak } = load('src/renderer/src/services/languageGuard.ts')
const { assertNativeReviewGate } = load('src/renderer/src/services/nativeReviewGate.ts')
const { findTextRepetitions } = load('src/shared/textRepetition.ts')
const { createEmptyProject } = load('src/renderer/src/types/index.ts')
const source = '「雨だ？？？！！」\nเด็กตั้งครรภ์ กำลังอ่าน ๒๐\n“Hello!!!” [文字] 😀✨\nGiá 3.5, giờ 10:30.'
const clean = plainNarration(source)
assert(!/[^\p{L}\p{M}\p{N}\s.,。、]/u.test(clean))
assert(clean.includes('ตั้งครรภ์') && clean.includes('กำลังอ่าน') && clean.includes('文字'))
assert(clean.includes('3.5'))
assert.equal(plainNarration(clean), clean)
const draft = '「鍵を戻した！」\n【扉】を閉めた。'
const raw = JSON.stringify({ edits: [], memory: { chapter: { summary: 'Done', events: [], state: [], openThreads: [] }, updates: [{ id: 'key', kind: 'object', subject: '鍵', text: '鍵を戻した。', status: 'current', importance: 'normal', related: [], evidenceSentenceId: 'S1' }] } })
const result = applyChapterCorrection(draft, raw)
const patch = applyMemoryPayload(createEmptyProject('test', 'Test'), 1, 0, true, result.text, result.memory)
assert(patch.memoryRecords[0].source.verified, 'evidence offsets remapped after quote removal')
assert.equal(result.text.slice(patch.memoryRecords[0].source.start, patch.memoryRecords[0].source.end), patch.memoryRecords[0].source.quote)
assert.throws(() => applyChapterCorrection('雨が降る。', JSON.stringify({ ...JSON.parse(raw), edits: [{ before: '雨が降る。', after: 'お'.repeat(8587) }] })), /MỚI/)
assert.throws(() => applyChapterCorrection('雨が降る。', JSON.stringify({ ...JSON.parse(raw), edits: [{ before: '雨が降る。', after: Array.from({length:100},(_,i)=>`Scene ${i} changes.`).join(' ') }] })), /quá nhiều/)
assert(findTextRepetitions('面白いwwwwwwww').length)
assert(!findTextRepetitions('www.example.com').length)
assert(hasTargetLanguageLeak('終わり。Thank you Haruto. You saved the world.', 'ja'))
assert(!hasTargetLanguageLeak('AIが動く。HPは100。', 'ja'))
assert.doesNotThrow(() => assertNativeReviewGate(JSON.stringify({ language:'ja',complete:true,chapterReview:{ complete: true, noRepeatedCompletion: true, noPrematureCompletion: true, knowledgeConsistent: true },issues:[{quote:'うおお。',suggestion:'「うおお！」',reason:'quotes only'}],unresolved:[] }), { language:'ja' }, 'うおお。'))
const app = harness([bad], [packet(), packet([{ repetitionId: 'R1', after: 'おお' }])], 'new')
app.store.setState({ projects: [{ ...app.project, language: 'ja', outline: { ...app.project.outline, chapters: app.project.outline.chapters.slice(0, 1) } }] })
await app.store.getState().confirmAndWrite()
assert.equal(app.store.getState().getActiveProject().generatedStory, good)
assert.equal(app.calls.length, 1)
assert.equal(app.chatCalls.length, 2)
assert(app.chatCalls[0][0].content.includes('repetitionId'))
assert(!app.saved.some(p => p.generatedStory === bad))
console.log('PASS: plain Unicode prose, no symbol noise, Japanese/Thai marks, exact memory mapping, new-corruption/growth rejection, English detection and typography gate conflict')
