function fenceFor(path) {
  const ext = path.split('.').pop()
  return FENCE_LANG[ext] ?? ''
}

const stamp = new Date().toISOString().slice(0, 19).replace('T', ' ')
let out = PREAMBLE.replace('{{TIMESTAMP}}', stamp)

for (const rel of FILES) {
  const content = readFileSync(join(ROOT, rel), 'utf-8').replace(/\s+$/, '')
  const displayPath = rel.replace(/\//g, '\\')
  out += `\n## \`${displayPath}\`\n\n\`\`\`${fenceFor(rel)}\n${content}\n\`\`\`\n\n---\n`
}

writeFileSync(join(ROOT, 'FULL_CODEBASE.md'), out, 'utf-8')
console.log(`FULL_CODEBASE.md updated — ${FILES.length} files, ${out.length.toLocaleString()} chars`)
